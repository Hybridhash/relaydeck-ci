"""Small live capabilities consumed by the HTTP routers."""

from __future__ import annotations

import asyncio
from collections.abc import AsyncIterator, Callable
from typing import Any, Protocol

from relaydeck.gateway.features.access.api import (
    AuthorizationFlow,
    EnrollmentStore,
    HostStore,
    IdentityProvider,
    PairingStore,
    SessionStore,
    TicketStore,
)
from relaydeck.gateway.features.metadata.api import InventoryView, MetadataStreams
from relaydeck.gateway.features.notifications.api import (
    NotificationTransitions,
    ProviderPort,
    PushStore,
)
from relaydeck.gateway.features.pictures.api import PictureStore
from relaydeck.gateway.features.terminals.api import Attachment, SocketRegistry, StreamFanout
from relaydeck.gateway.features.usage_read.api import UsageService
from relaydeck.gateway.http.middleware.metrics import Metrics
from relaydeck.gateway.ports import StreamBatch, TerminalLease
from relaydeck.git.api import GitReadPort


class Limit(Protocol):
    def check(self, key: str, now_ms: int, cost: float = 1.0) -> bool: ...


class NoticeSource(Protocol):
    host_id: str

    def document(self) -> dict[str, Any]: ...


class AgentsBackend(Protocol):
    def events_after(self, host_id: str, sequence: int) -> list[dict[str, Any]]: ...
    def snapshot(self, host_id: str) -> dict[str, Any]: ...


class CommandsBackend(Protocol):
    def drain_socket_closes(self) -> tuple[str, ...]: ...
    def snapshot(self, host_id: str) -> dict[str, Any]: ...


class DevicesBackend(Protocol):
    def revoke_leases_device(self, account: str, device_id: str) -> tuple[str, ...]: ...


class EventsBackend(Protocol):
    def follow(
        self, host_id: str, after_sequence: int, heartbeat_s: float = 15.0
    ) -> AsyncIterator[dict[str, Any] | None]: ...


class HostsBackend(Protocol):
    def snapshot(self, host_id: str) -> dict[str, Any]: ...


class IdentityBackend(Protocol):
    def revoke_leases_device(self, account: str, device_id: str) -> tuple[str, ...]: ...


class SocketsBackend(Protocol):
    def begin_reader_handoff(
        self, lease_id: str, account: str, device_id: str, generation: int
    ) -> bool: ...
    def fanout_for(self, attachment_id: str) -> StreamFanout | None: ...
    def finish_reader_handoff(
        self, lease_id: str, account: str, device_id: str, generation: int
    ) -> TerminalLease: ...
    def open_lease(self, lease_id: str) -> TerminalLease | None: ...
    def read_stream(self, lease_id: str, epoch: str, after_offset: int) -> StreamBatch: ...

    requires_connector: bool

    def write_input(
        self, lease_id: str, generation: int, input_seq: int, kind: str, data: bytes
    ) -> bool: ...


class TerminalsBackend(Protocol):
    def acquire_control(
        self,
        attachment_id: str,
        account: str,
        device_id: str,
        *,
        expected_generation: int | None = None,
    ) -> TerminalLease: ...
    def close_attachment(self, attachment_id: str, account: str) -> tuple[str, ...]: ...
    def control_holder(
        self, host_id: str, terminal_id: str, account: str, device_id: str
    ) -> dict[str, Any]: ...
    def create_attachment(
        self,
        host_id: str,
        terminal_id: str,
        kind: str,
        account: str,
        device_id: str,
        *,
        takeover: bool,
        owner_label: str = "",
        expected_control_revision: str | None = None,
    ) -> tuple[Attachment, tuple[str, ...]]: ...
    def get_attachment(self, attachment_id: str) -> Attachment | None: ...
    def issue_view(self, attachment_id: str, account: str, device_id: str) -> TerminalLease: ...
    def lease_host(self, lease_id: str) -> str | None: ...
    def open_lease(self, lease_id: str) -> TerminalLease | None: ...
    def renew_lease(self, lease_id: str, account: str, device_id: str) -> TerminalLease: ...


class UsageBackend(Protocol):
    def events_after(self, host_id: str, sequence: int) -> list[dict[str, Any]]: ...
    def snapshot(self, host_id: str) -> dict[str, Any]: ...


class AgentsCapabilities(Protocol):
    @property
    def backend(self) -> AgentsBackend: ...
    @property
    def cursor_secret(self) -> bytes: ...
    @property
    def inventory(self) -> InventoryView: ...


class CommandsCapabilities(Protocol):
    @property
    def backend(self) -> CommandsBackend: ...
    @property
    def commands(self) -> Limit: ...
    @property
    def now_ms(self) -> Callable[[], int]: ...
    @property
    def sockets(self) -> SocketRegistry: ...


class DevicesCapabilities(Protocol):
    @property
    def backend(self) -> DevicesBackend: ...
    @property
    def metadata(self) -> MetadataStreams: ...
    @property
    def metrics(self) -> Metrics: ...
    @property
    def now_ms(self) -> Callable[[], int]: ...
    @property
    def push(self) -> PushStore: ...
    @property
    def sessions(self) -> SessionStore: ...
    @property
    def sockets(self) -> SocketRegistry: ...


