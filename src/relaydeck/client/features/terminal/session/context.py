"""Capabilities used by the terminal session's callback builders."""

from __future__ import annotations

from collections.abc import Callable
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from relaydeck.client.features.composer.api import ComposerStore
    from relaydeck.client.features.terminal.controller import TerminalController
    from relaydeck.client.features.terminal.input_modes import InputModeState
    from relaydeck.client.features.terminal.keys import KeyInputSession
    from relaydeck.client.features.terminal.models import TerminalViewState
    from relaydeck.client.features.terminal.output_log import BoundedOutputLog
    from relaydeck.client.features.terminal.paste_review import PasteReviewSession
    from relaydeck.client.features.terminal.renewal import LeaseRenewalDriver
    from relaydeck.client.features.terminal.session.rendering import RendererBinding
    from relaydeck.client.ports.clipboard import ClipboardPort
    from relaydeck.client.ports.terminal import LeaseInfo, ShellGatewayOps
    from relaydeck.lease_diagnostics import LeaseTrace


class InputSessions(Protocol):
    @property
    def bound(self) -> bool: ...
    @property
    def epoch(self) -> int: ...
    @property
    def paste(self) -> PasteReviewSession: ...
    @property
    def keys(self) -> KeyInputSession: ...
    @property
    def modes(self) -> InputModeState: ...
    def bind(self, controller: TerminalController) -> None: ...
    def invalidate(self) -> str | None: ...


class SessionContext(Protocol):
    @property
    def _PHASE_EXITED(self) -> str: ...
    @property
    def _bracketed(self) -> bool: ...
    @property
    def _clipboard(self) -> ClipboardPort | None: ...
    @property
    def _controller(self) -> TerminalController | None: ...
    @property
    def _disposed(self) -> bool: ...
    @property
    def _foreground(self) -> bool: ...
    @property
    def _host_id(self) -> str: ...
    @property
    def _interaction_generation(self) -> int: ...
    @property
    def _lease(self) -> LeaseInfo | None: ...
    @property
    def _ops(self) -> ShellGatewayOps: ...
    @property
    def _paused(self) -> bool: ...
    @property
    def _phase(self) -> str: ...
    @property
    def _renderer(self) -> RendererBinding: ...
    @property
    def _sessions(self) -> InputSessions: ...
    @property
    def _term_state(self) -> TerminalViewState: ...
    @property
    def note_input(self) -> Callable[[], None]: ...
    @property
    def output_log(self) -> BoundedOutputLog: ...

    def _bump_epoch(self) -> None: ...

    def _bump_interaction(self, site: str) -> None: ...

    def _cancel_background_recovery(self) -> None: ...

    def _cancel_renewal_driver(self) -> None: ...

    async def _close_controller(self) -> None: ...

    def _composer_store(self) -> ComposerStore | None: ...

    def _detach_store(self) -> None: ...

    def _drop_controller(self) -> None: ...

    def _drop_lease(self) -> None: ...

    def _drops_engine_keys(self) -> bool: ...

    def _lease_trace(self, lease: LeaseInfo | None = None) -> LeaseTrace: ...

    def _mark_viewer_reopened(self, notice: str) -> None: ...

    def _note_stale_notice(self, stale: str | None) -> None: ...

    def _notify(self) -> None: ...

    def _on_renewal_terminal(self, code: str) -> None: ...

    def _operation_current(self, generation: int) -> bool: ...

    @property
    def _renewal(self) -> LeaseRenewalDriver | None: ...

    def _restart_renewal(self) -> None: ...

    def _set_term_state(self, state: TerminalViewState) -> None: ...

    def _terminal_label(self) -> str: ...

    @property
    def _workflow_kind(self) -> str: ...

    @property
    def current_term(self) -> object | None: ...

    @property
    def input_token(self) -> tuple[int, int] | None: ...

    @property
    def interaction_generation(self) -> int: ...

    async def request_paste(
        self, text: str, *, require_review: bool = False, from_app: bool = False
    ) -> str: ...
